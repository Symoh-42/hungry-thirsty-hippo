import type { ServiceId } from "@/data/services";

export type ReviewStatus = "pending" | "approved" | "rejected";

export interface Review {
  id: string;
  createdAt: string; // ISO
  services: ServiceId[];
  /** QR location slug the guest scanned, if any. */
  source?: string;
  overall: number; // 1-5
  /** Question key -> 1..5. Unanswered questions are absent. */
  ratings: Record<string, number>;
  enjoyed: string[];
  improve: string[];
  issueReasons: string[];
  delightReasons: string[];
  comment: string;
  guest: { name: string; email: string; phone: string };
  /** Guest agreed to have the review shown publicly. Only these can be approved. */
  publishConsent: boolean;
  status: ReviewStatus;
  resolved: boolean;
  response?: { text: string; at: string };
  /** Demonstration review generated by src/data/sampleReviews.ts. */
  sample?: boolean;
}

export type ReviewDraft = Omit<Review, "id" | "createdAt" | "status" | "resolved" | "response" | "sample">;
